-- ---------------------------------------------------------------------
-- 173 · หน้าจับคู่ย้ายออกไปฐานข้อมูลของตัวเองแล้ว · เก็บของเก่าที่นี่ทิ้ง
--
-- ─────────────────────────────────────────────────────────────────
-- ทำไมถึงย้ายออก
--
-- ไฟล์สองใบของหน้าจับคู่กินที่ราวเก้าสิบเปอร์เซ็นต์ของฐานข้อมูลนี้
-- ทั้งที่งานอื่นทุกงานรวมกัน ตั้งแต่การเบิกของ ปล่อยรถ บัตรเบรค ไปจนถึงทรัพย์สิน
-- ใช้รวมกันไม่ถึงยี่สิบเมกะไบต์ · แปลว่าหน้าเดียวหน้านี้เกือบทำให้ที่เหลือหมดที่อยู่
--
-- และของก้อนนี้เป็นของที่ทิ้งได้ · มันคือภาพของคลังในวันที่อัป อัปใหม่ทับได้ทุกเมื่อ
-- ต่างจากประวัติการเบิก รูปหลักฐาน หรือรายชื่อพนักงาน ซึ่งลบแล้วไม่มีทางได้คืน
-- ของที่ทิ้งได้ไม่ควรไปเบียดที่ของที่ทิ้งไม่ได้
--
-- ตอนนี้ข้อมูลจริงอยู่ฝั่งใหม่ครบแล้ว อัปทับไปเมื่อ 14 ต.ค. 2569
--   ไฟล์รายละเอียด 54,834 · ไฟล์สินค้า 60,146 · จับคู่ได้ 39,933
-- และหน้าเว็บที่ขึ้นหน้างานอยู่ตอนนี้ไม่เรียกฟังก์ชัน p48 ที่นี่แล้วแม้แต่ตัวเดียว
-- ─────────────────────────────────────────────────────────────────


-- ---------------------------------------------------------------------
-- ① กันพลาด · ถ้ายังมีอะไรอื่นนอกจากงานกลางคืนอ้างถึงอยู่ ให้ล้มทั้งไฟล์
--
-- ไม่ใช่พิธีกรรม · ตรงนี้คือการลบของสองร้อยกว่าเมกะไบต์แบบเอาคืนไม่ได้
-- ถ้าวันหน้ามีใครไปผูกอะไรไว้เพิ่มโดยที่ไฟล์นี้ไม่รู้ ต้องให้มันหยุดตั้งแต่บรรทัดนี้
-- ---------------------------------------------------------------------
do $guard$
declare v_names text;
begin
  select string_agg(p.proname, ', ')
    into v_names
    from pg_proc p
    join pg_namespace n on n.oid = p.pronamespace
   where n.nspname = 'public'
     and p.proname not like 'p48%'
     and p.proname <> '_p48_bench'
     and p.proname <> 'nightly_cleanup'
     and pg_get_functiondef(p.oid) ilike '%p48_%';

  if v_names is not null then
    raise exception 'ยังมีฟังก์ชันอื่นเรียก p48 อยู่ จึงยังลบไม่ได้ · %', v_names;
  end if;
end $guard$;


-- ---------------------------------------------------------------------
-- ② ทิ้งฟังก์ชันทั้งหมดของหน้าจับคู่
--
-- ไล่จากแคตตาล็อกแทนการไล่พิมพ์ชื่อทีละตัว เพราะพิมพ์เองคือมีวันลืมสักตัว
-- แล้วตัวที่ลืมจะอยู่ต่อไปอีกหลายปีโดยไม่มีใครรู้ว่ามันทำอะไร
-- ---------------------------------------------------------------------
do $drop_fn$
declare r record;
begin
  for r in
    select p.oid::regprocedure as sig
      from pg_proc p
      join pg_namespace n on n.oid = p.pronamespace
     where n.nspname = 'public'
       and (p.proname like 'p48%' or p.proname = '_p48_bench')
  loop
    execute format('drop function if exists %s cascade', r.sig);
  end loop;
end $drop_fn$;


-- ---------------------------------------------------------------------
-- ③ ทิ้งตาราง · ตรงนี้คือที่ที่พื้นที่จะคืนมาจริง ๆ
--
-- drop table คืนที่ทันทีตอน commit ต่างจาก delete ที่แค่ทำเครื่องหมายว่าว่าง
-- แล้วรอ autovacuum มาเก็บ ซึ่งเป็นสิ่งที่ทำ CPU ตันไปทั้งคืนเมื่อ 13 ต.ค.
-- ---------------------------------------------------------------------
drop table if exists p48_products cascade;
drop table if exists p48_parcels  cascade;
drop table if exists p48_sla      cascade;
drop table if exists p48_runs     cascade;


-- ---------------------------------------------------------------------
-- ④ คืน p48_sweep ไว้เป็นตัวเปล่า · อ่านชื่อแล้วอาจงงว่าทำไมไม่ลบให้หมด
--
-- งานทำความสะอาดกลางคืน nightly_cleanup() เรียกตัวนี้อยู่
-- ถ้าลบทิ้งเฉย ๆ งานกลางคืนจะพังตั้งแต่คืนนี้ และพังแบบเงียบ ๆ ตอนตีสาม
-- ซึ่งแปลว่างานทำความสะอาดของ ทุกตาราง หยุดไปด้วยโดยไม่มีใครรู้
--
-- ทางเลือกคือไปแก้ตัวงานกลางคืนเอง แต่นั่นคือการไปยุ่งกับของที่ยังทำงานดีอยู่
-- ด้วยการเดาว่าข้างในเขียนไว้ยังไง เพื่อประหยัดฟังก์ชันเปล่าไปหนึ่งตัว
-- ซึ่งไม่คุ้มกันเลย · ตัวเปล่านี้คืนศูนย์ ซึ่งเป็นคำตอบที่ตรงกับความจริง
-- เพราะที่นี่ไม่มีอะไรให้เก็บกวาดอีกแล้ว
--
-- วันไหนแก้ nightly_cleanup() ด้วยเหตุผลอื่นอยู่แล้ว ค่อยตัดบรรทัดนั้นแล้วลบตัวนี้ทิ้ง
-- ---------------------------------------------------------------------
create or replace function p48_sweep(p_limit integer default 0)
returns integer
language sql
security definer
set search_path = public
as $$ select 0 $$;

revoke all on function p48_sweep(integer) from public, anon, authenticated;

comment on function p48_sweep(integer) is
  'ตัวเปล่าที่เหลือไว้ให้ nightly_cleanup() เรียกได้ · ข้อมูลหน้าจับคู่ย้ายออกไปตั้งแต่ migration 173';


-- ---------------------------------------------------------------------
-- ⑤ ตรวจผล
--
-- ไม่เรียก nightly_cleanup() มาลองตรงนี้ เพราะมันจะไปลบของจริงของตารางอื่น
-- การตรวจที่ถูกต้องคือดูว่าตัวที่มันเรียกยังมีอยู่ ไม่ใช่ไปกดให้มันทำงาน
-- ---------------------------------------------------------------------
select
  (select count(*) from pg_class c join pg_namespace n on n.oid = c.relnamespace
    where n.nspname = 'public' and c.relkind = 'r' and c.relname like 'p48%')  as ตารางที่เหลือ,
  (select string_agg(p.proname, ', ') from pg_proc p
     join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname like 'p48%')                      as ฟังก์ชันที่เหลือ,
  (select count(*) from pg_proc p join pg_namespace n on n.oid = p.pronamespace
    where n.nspname = 'public' and p.proname = 'p48_sweep')                    as ตัวเปล่ายังอยู่,
  pg_size_pretty(pg_database_size(current_database()))                         as ขนาดฐานข้อมูล;
