-- 072 · ย่อโค้ดในบัตร OS ให้ QR สแกนง่ายขึ้น
--
-- ของเดิม gen_random_bytes(24) แปลงเป็น base64 ได้ข้อความ 32 ตัว
-- ตัวพิมพ์เล็กใหญ่ปนกัน QR จึงต้องเข้ารหัสแบบไบต์ ใช้ตาราง 29x29 ช่อง
-- ยัดลงบัตรกว้าง 54 มม. แล้วเหลือช่องละ 0.47 มม. ซึ่งเล็กเกินกว่ากล้องจะจับไว
-- รปภ ต้องยืนส่ายมือถืออยู่หน้าคน ทั้งที่งานนี้ต้องเร็วตอนคนเข้ากะพร้อมกัน
--
-- 16 ตัวพิมพ์ใหญ่ล้วน QR เข้ารหัสแบบตัวอักษรได้ เหลือตาราง 21x21
-- ขนาดเท่าเดิมแต่ช่องโตขึ้นเกือบเท่าตัว
--
-- ความปลอดภัยเท่าเดิมในทางปฏิบัติ 16 ตัวจาก 32 อักษร = ความสุ่ม 80 บิต
-- และการเดาต้องยิงผ่าน os_scan ซึ่งบันทึกทุกครั้งที่เรียกอยู่แล้ว
--
-- ของเก่าที่ออกไปแล้วยังสแกนได้ปกติ เพราะ os_scan เทียบข้อความตรง ๆ
-- ไม่ได้สนรูปแบบหรือความยาว ไฟล์นี้จึงเปลี่ยนแค่โค้ดที่จะออกใหม่นับจากนี้

create or replace function os_new_token() returns text
language sql volatile set search_path = public, extensions as $$
  -- อักษรแบบ Crockford ตัด I L O U ทิ้ง เพราะอ่านสลับกับ 1 กับ 0 ได้
  -- โค้ดนี้มีวันที่ต้องอ่านด้วยตาตอน QR เปื้อนหรือบัตรหัก
  -- ทั้ง 32 ตัวอยู่ในชุดอักษรที่ QR เข้ารหัสแบบตัวอักษรได้หมด
  --
  -- 256 หารด้วย 32 ลงตัว การมอดจึงไม่ทำให้ตัวไหนออกบ่อยกว่าตัวอื่น
  select string_agg(
           substr('0123456789ABCDEFGHJKMNPQRSTVWXYZ',
                  (get_byte(s.b, i) % 32) + 1, 1),
           '' order by i
         )
  from (select gen_random_bytes(16) as b) s,
       generate_series(0, 15) as i
$$;
