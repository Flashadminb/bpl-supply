--
-- ไล่มาตามลำดับ เจ้าของระบบคนเดียว แล้วเพิ่มผู้ตรวจสอบ ตอนนี้เปิดให้หน้างานทุกคน
-- ซึ่งกลับไปตรงกับที่สั่งไว้ตั้งแต่วันแรกว่า "ทุกคนพิมพ์ได้"
--
-- เปิดเฉพาะตัวงาน ดูกระดาน เพิ่มรถ ปล่อยรถ ดูจอทีวีและสถิติ
-- งานหลังบ้านยังเป็นของผู้ดูแลระบบคนเดียวเหมือนเดิม
-- ส่งลงชีต ลบของเก่า แก้รายชื่อสาขา ตั้งแจ้งเตือน และรีเซตตัวนับจอทีวี
-- นั่นคืองานที่กดผิดแล้วกระทบของจริง ไม่ใช่งานประจำวัน
--
-- บัญชีที่ถูกระงับยังเข้าไม่ได้ เพราะเช็ค is_active ไม่ใช่เช็คว่าล็อกอินอยู่เฉย ๆ
-- =====================================================================

create or replace function my_can_truck() returns boolean
language sql stable security definer set search_path = public as $$
  select coalesce((select is_active from profiles where id = auth.uid()), false);
$$;

grant execute on function my_can_truck() to authenticated;


-- ---------------------------------------------------------------------
-- ตรวจผล
-- ---------------------------------------------------------------------
select
  (select count(*) from pg_proc
    where proname = 'my_can_truck' and prosrc like '%is_active%')  as เปิดให้ทุกคนแล้ว,
  (select count(*) from profiles where is_active)                  as คนที่เข้าได้ตอนนี้,
  (select count(*) from profiles where is_active and role = 'staff') as เป็นหน้างาน;
