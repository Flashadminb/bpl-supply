-- เกิดอะไรขึ้น
--
-- 14 ต.ค. เช้า ผมสั่งสำรองรอบทดสอบตอนหน้างานกำลังใช้อยู่
-- รปภ แจ้งว่าสแกนบัตรเบรคไม่ได้ หน้าจอหมุนค้าง
--
-- กราฟชี้ชัด · IOwait พุ่งไป 75-80% ตรงกับเวลาที่สั่งสำรองพอดี
-- ไม่มี ERROR สักบรรทัด เพราะไม่มีอะไรพัง · ดิสก์แค่ถูกยึดไว้คนเดียว
-- จนทุกคำสั่งของหน้างานต้องต่อคิว ซึ่งคนที่ยืนอยู่หน้าประตูเห็นเป็นวงกลมหมุน
--
-- ลายเซ็นเดียวกับคืน 13 ต.ค. เป๊ะ ซึ่งเป็นเหตุการณ์ที่วิเคราะห์ไว้เองแล้วแท้ ๆ
-- ─────────────────────────────────────────────────────────────────
--
-- ทางแก้ที่ไม่ใช่การหาเวลาเงียบ
--
-- ถามเจ้าของระบบแล้วว่าช่วงไหนของสัปดาห์ฮับเงียบที่สุด คำตอบคือตอบยาก
-- แล้วแต่งานที่เข้ามา บางทีเที่ยงคืนวันอาทิตย์ บางทีวันพุธ
--
-- คำตอบนั้นถูกแล้ว และมันแปลว่าการเลือกเวลาไม่ใช่คำตอบ
-- ต้องทำให้งานสำรองเบาพอที่จะรันตอนไหนก็ไม่กระทบใคร
-- และรู้จักหยุดรอเองเมื่อเห็นว่าหน้างานกำลังยุ่ง
-- ---------------------------------------------------------------------


-- ---------------------------------------------------------------------
-- ตอนนี้มีคนใช้งานอยู่หนาแน่นแค่ไหน
--
-- นับเฉพาะคำสั่งของผู้ใช้จริงที่กำลังทำงานอยู่ ไม่นับตัวเอง
-- ไม่นับงานเบื้องหลังของ Postgres เอง และไม่นับการเชื่อมต่อที่นั่งว่าง
-- เพราะการเชื่อมต่อที่เปิดค้างไว้เฉย ๆ ไม่ได้แย่งดิสก์กับใคร
--
-- ตัวเลขนี้ให้ฝั่ง Edge Function ถามก่อนเริ่มอ่านตารางถัดไป
-- เห็นว่ายุ่งก็รอ · เห็นว่าว่างก็ทำต่อ · เป็นการหลบเองโดยไม่ต้องรู้ตารางเวลาของใคร
-- ---------------------------------------------------------------------
create or replace function backup_busy()
returns integer
language sql
stable
security definer
set search_path = public
as $$
  select count(*)::integer
    from pg_stat_activity
   where datname = current_database()
     and state = 'active'
     and pid <> pg_backend_pid()
     and backend_type = 'client backend'
$$;

revoke all on function backup_busy() from public, anon, authenticated;
grant execute on function backup_busy() to service_role;

comment on function backup_busy() is
  'มีคำสั่งของผู้ใช้กำลังทำงานอยู่กี่คำสั่ง · งานสำรองใช้ตัวนี้ตัดสินใจว่าจะรอหรือไปต่อ';


-- ---------------------------------------------------------------------
-- ยังไม่ตั้งเวลาในไฟล์นี้
--
-- ตั้งใจไม่ตั้ง · จะเปิดใช้ต่อเมื่อพิสูจน์แล้วว่ารุ่นใหม่เบาจริง
-- ของที่เคยทำหน้างานเดือดร้อนมาแล้วหนึ่งครั้ง ไม่ควรกลับมาเองเงียบ ๆ
--
-- เปิดใช้ด้วยคำสั่งนี้เมื่อพร้อม · เที่ยงคืนวันอาทิตย์ตามเวลาไทย = 17:00 UTC วันเสาร์
--   select cron.schedule('bpl-weekly-backup', '0 17 * * 6', 'select backup_tick()');
-- ---------------------------------------------------------------------

select
  (select count(*) from pg_proc where proname = 'backup_busy')          as มีฟังก์ชันแล้ว,
  backup_busy()                                                          as กำลังยุ่งอยู่กี่คำสั่ง,
  (select count(*) from cron.job where jobname = 'bpl-weekly-backup')   as ตั้งเวลาไว้หรือยัง;
