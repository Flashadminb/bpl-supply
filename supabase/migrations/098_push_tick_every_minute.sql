-- รันต่อจาก 097 · ปลอดภัยที่จะรันซ้ำ
--
-- เบรคเกินเวลาเตือนหัวหน้างานคนที่ปล่อยบัตรอยู่แล้วตั้งแต่ 081
-- แต่เดินนาฬิกาทุก 5 นาที ขอเบรค 10 นาทีแล้วเลยเวลา จึงอาจได้เตือนตอนนาทีที่ 14
-- ซึ่งสายเกินกว่าจะเรียกว่าเตือน · เวลาที่ช้าไปคือเวลาที่คนยังอยู่ข้างนอกโดยไม่มีใครรู้
--
-- ไม่ได้แก้ที่ตัวงานเตือน แก้ที่ความถี่ของนาฬิกาอย่างเดียว
-- ทุกอย่างที่เตือนอยู่แล้วจึงตรงเวลาขึ้นตามไปด้วย ประชุม ของค้างคืน เบรค
--
-- ส่งซ้ำไหม — ไม่ · notification_log จำไว้ว่าเรื่องไหนส่งให้ใครไปแล้ว
-- รอบที่ไม่มีอะไรใหม่จะได้งานศูนย์ชิ้นแล้วจบ ไม่ได้ยิงอะไรออกไป
--
-- เปลืองโควตาไหม — ไม่ · เดิมวันละ 288 รอบ เป็นวันละ 1,440 รอบ
-- เดือนละราวสี่หมื่นครั้ง จากโควตา Edge Function ฟรีห้าแสนครั้งต่อเดือน
-- =====================================================================

do $$
begin
  perform cron.unschedule('bpl-push-tick');
exception when others then
  null; -- ยังไม่เคยตั้ง หรือ pg_cron ยังไม่พร้อม
end $$;

do $$
begin
  perform cron.schedule('bpl-push-tick', '* * * * *', 'select push_tick()');
  raise notice 'ตั้งนาฬิกาแจ้งเตือนใหม่เรียบร้อย เดินทุกนาที';
exception when others then
  raise notice 'ตั้งนาฬิกาไม่สำเร็จ (%) — เปิด pg_cron ที่ Dashboard แล้วรันไฟล์นี้ซ้ำ', sqlerrm;
end $$;


-- ---------------------------------------------------------------------
-- ตรวจผล
--
-- schedule ต้องเป็น * * * * * และ active ต้องเป็น true
-- ---------------------------------------------------------------------
select jobname, schedule, active, command
  from cron.job
 where jobname = 'bpl-push-tick';
