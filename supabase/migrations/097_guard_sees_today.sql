-- BPL SUPPLY — รปภ เห็นประวัติการปล่อยของวันนี้ ไม่ใช่แค่ใบที่ยังค้าง
-- รันต่อจาก 096 · ปลอดภัยที่จะรันซ้ำ
--
-- ของเดิม รปภ อ่านได้เฉพาะใบที่ยังไม่ปิด พอกดรับกลับปุ๊บใบนั้นหายจากจอทันที
-- ซึ่งทำให้ตอบคำถามที่เกิดขึ้นจริงที่ประตูไม่ได้เลย
--   "บัตรใบนี้เมื่อกี้ออกไปตอนกี่โมง" · "ใบนี้เพิ่งกลับไปแล้วใช่ไหม"
--   "วันนี้ใบนี้ออกไปกี่รอบแล้ว"
-- รปภ ต้องเดาเอง หรือโทรถามหลังบ้าน ทั้งที่ข้อมูลอยู่ในมือถือเขาอยู่แล้ว
--
-- เปิดให้อ่านย้อนหลัง 24 ชั่วโมง ไม่ใช่ทั้งหมด
-- พอสำหรับกะที่ยาวที่สุดและคาบเกี่ยวข้ามกะ แต่ไม่กลายเป็นคลังประวัติทั้งฮับ
--
-- ของในใบไม่มีข้อมูลส่วนตัวของ OS อยู่แล้วตั้งแต่ออกแบบ
-- มีแค่รหัสบัตร เหตุผล จำนวนคน และเวลา การเปิดให้ รปภ อ่านจึงไม่เพิ่มความเสี่ยง
-- ส่วนรูปหลักฐานอยู่คนละตาราง และ policy ของมันไม่ได้ถูกแตะในไฟล์นี้
-- =====================================================================

drop policy if exists read_break_passes on break_passes;
create policy read_break_passes on break_passes for select to authenticated using (
  my_can_audit()
  or issued_by = auth.uid()
  -- รปภ · ใบที่ยังค้างเห็นได้เสมอ บวกย้อนหลัง 24 ชั่วโมงไว้ตอบคำถามที่ประตู
  or (my_can_break_guard() and (closed_at is null or issued_at > now() - interval '24 hours'))
  or (
    closed_at is null
    and my_can_break_issue()
    and exists (
      select 1 from break_group_users g
       where g.group_code = break_passes.group_code and g.user_id = auth.uid()
    )
  )
);


-- ---------------------------------------------------------------------
-- ตรวจผล
--
-- นับจากมุมของ postgres ตรง ๆ ไม่ได้ เพราะ policy ขึ้นกับว่าใครเป็นคนถาม
-- ดูได้แค่ว่า policy ถูกเขียนทับแล้วจริง และมีใบอยู่กี่ใบในช่วง 24 ชั่วโมง
-- ---------------------------------------------------------------------
select
  (select count(*) from pg_policies
    where tablename = 'break_passes' and policyname = 'read_break_passes')  as policyที่ใช้อยู่,
  (select count(*) from break_passes
    where issued_at > now() - interval '24 hours')                          as ใบในช่วง24ชั่วโมง,
  (select count(*) from break_passes where closed_at is null)               as ใบที่ยังค้าง;
