-- รัน "หลังจาก" นำเข้าพนักงานเสร็จแล้วเท่านั้น · ปลอดภัยที่จะรันซ้ำ
--
-- ที่มา: ชีต MASTER แท็บเงื่อนไข บรรทัด seeall
--   PP    → 617613, 721823, 721644, 646714
--   IDATA → 731495, 755310   (สองคนนี้อยู่ "ทุกแผนก" อยู่แล้ว เห็นครบโดยไม่ต้องทำอะไร)
--   755000 ไม่มีอยู่ในรายชื่อพนักงาน จึงตัดออกตามที่เจ้าของระบบสั่ง
--
-- หมายเหตุ: ระบบนี้ให้สิทธิ์เป็นราย "คน" ไม่ได้แยกตามประเภทเครื่อง
-- สี่คนนี้จึงเห็นเครื่องของทุกแผนก ไม่ใช่เฉพาะ Power Pallet
-- ถ้าอยากให้แคบกว่านั้น เปลี่ยน '{ALL}' เป็นรายชื่อแผนกที่ต้องการ
-- เช่น '{BULKY,INLHBG}' แล้วรันใหม่
-- =====================================================================

update profiles
   set extra_depts = '{ALL}'
 where employee_code in ('617613', '721823', '721644', '646714');

-- ดูผลลัพธ์
select employee_code, full_name, dept_code, extra_depts, shift_start, shift_end
  from profiles
 where employee_code in ('617613', '721823', '721644', '646714', '731495', '755310')
 order by employee_code;
