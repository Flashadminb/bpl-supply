const START_B = 104
const STOP = 106

/** อักขระที่ชุด B รับได้ · นอกช่วงนี้แปลงไม่ได้ */
export function canEncode128(text: string): boolean {
  if (!text) return false
  for (const ch of text) {
    const c = ch.charCodeAt(0)
    if (c < 32 || c > 126) return false
  }
  return true
}

/**
 * แปลงข้อความเป็นความกว้างของแถบ เริ่มที่แถบดำ
 *
 * คืน null เมื่อแปลงไม่ได้ · ฝั่งที่เรียกต้องไม่วาดอะไรเลยเมื่อได้ null
 */
export function code128Bars(text: string): number[] | null {
  if (!canEncode128(text)) return null

  const values: number[] = [START_B]
  for (const ch of text) values.push(ch.charCodeAt(0) - 32)

  /* เลขตรวจสอบ · ตัวเริ่มคูณหนึ่ง ตัวข้อมูลคูณตามลำดับที่ตั้งแต่หนึ่ง */
  let sum = START_B
  for (let i = 1; i < values.length; i++) sum += values[i] * i
  values.push(sum % 103)
  values.push(STOP)

  const bars: number[] = []
  for (const v of values) for (const d of PATTERNS[v]) bars.push(Number(d))
  return bars
}

/**
 * รูปบาร์โค้ดเป็น SVG พร้อมวาง
 *
 * ใช้ viewBox ให้ยืดเต็มกรอบที่วางเอง · ความคมไม่ขึ้นกับขนาดจอ
 * ต่างจาก canvas ที่ต้องรู้ขนาดจริงก่อนวาดและเบลอเมื่อถูกขยาย
 *
 * ขอบขาวซ้ายขวาอย่างละสิบหน่วยตามมาตรฐาน · ขาดตรงนี้เครื่องยิงจะหาหัวท้ายไม่เจอ
 */
export function code128Svg(text: string, barHeight = 44): string | null {
  const bars = code128Bars(text)
  if (!bars) return null

  const QUIET = 10
  const total = bars.reduce((a, b) => a + b, 0) + QUIET * 2

  let x = QUIET
  let d = ''
  bars.forEach((w, i) => {
    if (i % 2 === 0) d += `M${x} 0h${w}v${barHeight}h-${w}z`
    x += w
  })

  return (
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${total} ${barHeight}" ` +
    `preserveAspectRatio="none" shape-rendering="crispEdges">` +
    `<rect width="${total}" height="${barHeight}" fill="#fff"/>` +
    `<path d="${d}" fill="#000"/></svg>`
  )
}
