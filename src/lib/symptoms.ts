/**
 * อาการสำเร็จรูป — กดทีเดียวแทนการพิมพ์
 *
 * หน้างานใส่ถุงมือ พิมพ์ข้อความยาว ๆ ไม่ไหว ถ้าบังคับพิมพ์คนจะเลี่ยงไม่แจ้ง
 * แล้วปัญหาจะไปโผล่ตอนของพังหนักแล้วซึ่งสายเกินแก้
 *
 * แยกสองชุดตามจังหวะ เพราะความรับผิดชอบคนละเรื่อง
 *   out = เสียมาก่อนที่เราจะรับมา · แจ้งไว้กันโดนโทษทีหลัง
 *   in  = เสียระหว่างที่เราใช้งาน · เป็นเรื่องที่ต้องตามต่อ
 * ถ้าใช้คำเดียวกันทั้งสองจังหวะ พอย้อนดูจะแยกไม่ออกว่าใครทำพัง
 */

/** ของหาย — ต้องถึงมือแอดมินเดี๋ยวนั้น ไม่ใช่รอรอบนาฬิกา */
export const LOST = 'สูญหาย'

/**
 * อาการตามประเภทเครื่อง — ชุดคำที่เจ้าของระบบกำหนด
 *
 * รถแดงเป็นเครื่องจักร อาการจึงเป็นเรื่องกลไกและตัวถัง
 * ไอดาต้าเป็นเครื่องมือถือ อาการจึงเป็นเรื่องจอ แบต และของหาย
 */
const BY_TYPE: Record<string, { out: string[]; in: string[] }> = {
  PP: {
    out: ['กุญแจหาย/พัง', 'ช่องเสียบพัง', 'แบตเสื่อม', 'มีรอยขูด'],
    in: ['กุญแจหาย/พัง', 'ช่องเสียบพัง', 'แบตเสื่อม', 'มีรอยขูด'],
  },
  IDATA: {
    out: [LOST, 'แบตเสื่อม', 'ฝาหาย', 'จอแตก', 'มีอัพเดท'],
    in: [LOST, 'แบตเสื่อม', 'ฝาหาย', 'จอแตก', 'มีอัพเดท'],
  },
  LASER: {
    out: [LOST, 'แบตเสื่อม', 'ฝาหาย', 'จอแตก', 'มีอัพเดท'],
    in: [LOST, 'แบตเสื่อม', 'ฝาหาย', 'จอแตก', 'มีอัพเดท'],
  },
  RADIO: {
    out: [LOST, 'แบตเสื่อม', 'เสาอากาศหัก', 'เสียงดับ ๆ ติด ๆ', 'ปุ่มกดฝืด'],
    in: [LOST, 'แบตเสื่อม', 'เสาอากาศหัก', 'เสียงดับ ๆ ติด ๆ', 'ปุ่มกดฝืด'],
  },
  // เครื่องลาเบลพกพา · อาการเป็นเรื่องหัวพิมพ์ กระดาษ และการเชื่อมต่อ
  LABEL: {
    out: [LOST, 'พิมพ์ไม่ออก', 'กระดาษติด', 'แบตเสื่อม', 'ต่อบลูทูธไม่ได้', 'ฝาหาย'],
    in: [LOST, 'พิมพ์ไม่ออก', 'กระดาษติด', 'แบตเสื่อม', 'ต่อบลูทูธไม่ได้', 'ฝาหาย'],
  },
}

const FALLBACK = [LOST, 'แบตเสื่อม', 'มีรอยขูด', 'ใช้งานไม่ได้']

/**
 * รายการอาการของประเภทนี้
 *
 * ประเภทที่ไม่ได้ระบุไว้จะได้ชุดกลาง ซึ่งมี "สูญหาย" ติดมาด้วยเสมอ
 * เพราะของหายใช้ได้กับทุกอย่าง และเป็นอาการที่ต้องรู้ให้เร็วที่สุด
 */
export function symptomsFor(typeCode: string, phase: 'out' | 'in'): string[] {
  const key = Object.keys(BY_TYPE).find((k) => typeCode.toUpperCase().startsWith(k))
  return key ? BY_TYPE[key][phase] : FALLBACK
}

/** ของหายต้องเด้งหาแอดมินทันที หน้าจอจึงต้องบอกคนกดด้วยว่ากำลังจะเกิดอะไร */
export function isLost(text: string): boolean {
  return text.includes(LOST)
}
