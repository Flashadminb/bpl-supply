import { useEffect } from 'react'
import { useLocation } from 'react-router-dom'

/**
 * ชื่อบนแท็บเบราว์เซอร์ · ให้แต่ละหน้าต่างกัน
 *
 * ของเดิมทุกหน้าใช้ชื่อเดียวกันหมดคือ "BPL SUPPLY — เบิก/คืนวัสดุสิ้นเปลือง"
 * เปิดห้าแท็บแล้วหาไม่เจอว่าหน้าไหนคือหน้าไหน
 *
 * ชื่อหน้าอยู่ "หน้า" ชื่อระบบเสมอ ไม่ใช่ต่อท้าย
 * เพราะแท็บเบราว์เซอร์ตัดข้อความจากทางขวา ถ้าเอาชื่อระบบขึ้นก่อน
 * ทุกแท็บจะเหลือแต่คำว่า BPL SUPPLY เหมือนกันหมด ซึ่งคือปัญหาเดิมเป๊ะ ๆ
 *
 * ─────────────────────────────────────────────────────────────────
 * มีคนเขียนชื่อแท็บสองที่ · ตัวนับคำขอรออนุมัติก็เขียน
 * ถ้าต่างคนต่างเขียน useEffect จะแย่งกันแล้วชื่อกระพริบไปมา
 * จึงรวมมาเขียนที่ apply() ที่เดียว สองฝั่งแค่บอกค่าของตัวเองเข้ามา
 */

const BRAND = 'BPL SUPPLY'

/** ชื่อที่หน้ารู้จักตัวเอง · แถบหัวฝั่งแอพ กับเมนูฝั่งหลังบ้าน */
let page = ''
/** ชื่อสำรองที่เดาจาก path · ใช้กับหน้าที่ไม่มีทั้งสองอย่าง เช่นกระดานปล่อยรถ */
let fallback = ''
let badge = 0

/*
  แยกสองตัวแปรเพราะลำดับการทำงานของ effect เชื่อไม่ได้
  ลูกทำงานก่อนแม่ ถ้าใช้ตัวแปรเดียว ตัวสำรองของแม่จะทับชื่อจริงของลูกเสมอ
  แยกกันแล้วชื่อจริงชนะตลอด ไม่ต้องสนว่าใครทำงานก่อน
*/
function apply() {
  const name = page || fallback
  const head = name ? `${name} · ${BRAND}` : BRAND
  document.title = badge > 0 ? `(${badge}) ${head}` : head
}

/** ตัวเลขคำขอรออนุมัติที่นำหน้าชื่อแท็บ · 0 = ไม่ขึ้น */
export function setTitleBadge(n: number) {
  badge = n
  apply()
}

/**
 * ชื่อหน้าที่ไม่มีแถบหัวและไม่ได้อยู่ในหลังบ้าน
 *
 * กระดานปล่อยรถ รถรอลงงาน ของค้างส่งออก พัสดุ 24 ชม จอทีวี
 * พวกนี้เป็นหน้าเต็มจอไม่มีแถบหัว จึงไม่มีใครรู้ชื่อมันนอกจากตารางนี้
 *
 * ชื่อตรงกับชื่อในเมนูหลังบ้าน · เพิ่มหน้าใหม่แล้วอยากให้แท็บมีชื่อ เติมที่นี่
 * ไม่เติมก็ไม่พัง แค่ได้ชื่อระบบเฉย ๆ เหมือนก่อน
 */
const BY_PATH: [string, string][] = [
  ['/trucks/tv', 'จอทีวีปล่อยรถ'],
  ['/trucks/stats', 'สถิติปล่อยรถ'],
  ['/trucks/history', 'ประวัติปล่อยรถ'],
  ['/trucks', 'กระดานปล่อยรถ'],
  ['/wait/tv', 'จอทีวีรถรอลงงาน'],
  ['/wait/stats', 'แดชบอร์ดรถรอลงงาน'],
  ['/wait/history', 'ประวัติรถรอลงงาน'],
  ['/wait', 'กระดานรถรอลงงาน'],
  ['/outbox', 'ของค้างส่งออก'],
  ['/parcel24', 'พัสดุค้างเกิน 24 ชม'],
  ['/parcel48', 'จับคู่'],
  ['/guard', 'สแกนบัตร'],
  ['/break/board', 'บัตรเบรคของฉัน'],
  ['/break', 'บัตรเบรค'],
  ['/assets/done', 'เบิกสำเร็จ'],
  ['/assets', 'เบิก Asset'],
  ['/success', 'เบิกสำเร็จ'],
  ['/scan', 'สแกน'],
  ['/login', 'เข้าสู่ระบบ'],
  ['/admin', 'หลังบ้าน'],
  ['/', 'หน้าแรก'],
]

/**
 * ตั้งชื่อสำรองจาก path · เรียกครั้งเดียวที่ตัวบนสุดของแอพ
 * หน้าไหนมีชื่อจริงของตัวเองอยู่แล้ว ชื่อจริงชนะเสมอ ตัวนี้ไม่ไปทับ
 */
export function useFallbackTitle() {
  const { pathname } = useLocation()
  useEffect(() => {
    /* เทียบจากตัวที่ path ยาวสุดก่อน เพราะ / ตรงกับทุกหน้า
       และ /trucks ตรงกับ /trucks/tv ด้วย */
    const hit = BY_PATH.find(
      ([p]) => pathname === p || (p !== '/' && pathname.startsWith(p + '/')),
    )
    fallback = hit ? hit[1] : ''
    apply()
  }, [pathname])
}

/**
 * ตั้งชื่อหน้าปัจจุบัน · ชื่อที่หน้ารู้จักตัวเอง
 *
 * เรียกจากที่ที่รู้ชื่ออยู่แล้ว — แถบหัวของฝั่งแอพ และเมนูของฝั่งหลังบ้าน
 * จึงไม่ต้องไล่แก้ทีละหน้าสี่สิบกว่าไฟล์ และไม่มีตารางชื่ออีกชุดให้ลืมอัปตามเมนู
 */
export function usePageTitle(name: string | null | undefined) {
  useEffect(() => {
    page = (name ?? '').trim()
    apply()
    return () => {
      page = ''
      apply()
    }
  }, [name])
}
