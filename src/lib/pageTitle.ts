import { useEffect } from 'react'

/**
 * ชื่อบนแท็บเบราว์เซอร์ · ให้แต่ละหน้าต่างกัน
 *
 * ของเดิมทุกหน้าใช้ชื่อเดียวกันหมดคือ "BPL SUPPLY — เบิก/คืนวัสดุสิ้นเปลือง"
 * เปิดห้าแท็บแล้วหาไม่เจอว่าหน้าไหนคือหน้าไหน
 *
 * ชื่อหน้าอยู่ "หน้า" ชื่อระบบเสมอ ไม่ใช่ต่อท้าย
 * เพราะแท็บเบราว์เซอร์ตัดข้อความจากทางขวา ถ้าเอาชื่อระบบขึ้นก่อน
 * ทุกแท็บจะเหลือแต่คำว่า BPL SUPPLY เหมือนกันหมด ซึ่งคือปัญหาเดิมเป๊ะ ๆ
 *
 * ─────────────────────────────────────────────────────────────────
 * มีคนเขียนชื่อแท็บสองที่ · ตัวนับคำขอรออนุมัติก็เขียน
 * ถ้าต่างคนต่างเขียน useEffect จะแย่งกันแล้วชื่อกระพริบไปมา
 * จึงรวมมาเขียนที่ apply() ที่เดียว สองฝั่งแค่บอกค่าของตัวเองเข้ามา
 */

const BRAND = 'BPL SUPPLY'

let page = ''
let badge = 0

function apply() {
  const head = page ? `${page} · ${BRAND}` : BRAND
  document.title = badge > 0 ? `(${badge}) ${head}` : head
}

/** ตัวเลขคำขอรออนุมัติที่นำหน้าชื่อแท็บ · 0 = ไม่ขึ้น */
export function setTitleBadge(n: number) {
  badge = n
  apply()
}

/**
 * ตั้งชื่อหน้าปัจจุบัน
 *
 * เรียกจากที่เดียวที่รู้ชื่อหน้าอยู่แล้ว — แถบหัวของฝั่งแอพ
 * และเมนูของฝั่งหลังบ้าน จึงไม่ต้องไปไล่แก้ทีละหน้าสี่สิบกว่าไฟล์
 * และไม่ต้องมีตารางชื่อหน้าอีกชุดที่วันหนึ่งจะลืมอัปตามเมนู
 */
export function usePageTitle(name: string | null | undefined) {
  useEffect(() => {
    page = (name ?? '').trim()
    apply()
    return () => {
      page = ''
      apply()
    }
  }, [name])
}
